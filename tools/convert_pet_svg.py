#!/usr/bin/env python3
"""Convert selected local mascot SVG frame groups to Clawdmeter's 55x37 stage.

Uses only Python's standard library. The generated header is committed so a
firmware build does not depend on either sibling source checkout.
"""
import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

STAGE_W, STAGE_H = 55, 37
SCALE = 5.0  # five SVG units per Clawdmeter art cell
SCENES = (
    ("pet breathe", "desktop", "idle-breathe.svg"),
    ("pet look around", "desktop", "idle-look-around.svg"),
    ("pet thinking", "mascot", "thinking.svg"),
    ("pet typing", "mascot", "typing.svg"),
    ("pet waiting", "mascot", "waiting-for-you.svg"),
    ("pet greeting", "mascot", "greeting.svg"),
    ("pet asleep", "mascot", "asleep.svg"),
    ("pet done", "mascot", "done.svg"),
    ("pet coffee", "mascot", "gag-coffee.svg"),
)
COLORS = {
    "var(--cm-color, #DD775B)": 0xDBAA,
    "var(--cm-ink, #000000)": 0x0000,
    "#FFFDF5": 0xFFDE,
    "#C87392": 0xC392,
    "#DD8361": 0xDC0C,
    "#CB708F": 0xC38F,
    "#7CA4D0": 0x7D1A,
    "#70685D": 0x734B,
    "#D9A441": 0xDD28,
    "#704B32": 0x7246,
}


def scene(path):
    root = ET.parse(path).getroot()
    style = "".join(root.itertext())
    match = re.search(r"calc\(([0-9.]+)s \* var\(--cm-tempo", style)
    if not match:
        raise ValueError(f"no animation duration: {path}")
    duration_ms = round(float(match.group(1)) * 1000)
    groups = [node for node in root.iter()
              if "cm-frame" in node.attrib.get("class", "").split()]
    if not groups:
        raise ValueError(f"no animation frames: {path}")
    frames = []
    palette = [0]  # transparent; black remains a visible palette entry
    color_index = {}
    for group in groups:
        pixels = [0] * (STAGE_W * STAGE_H)
        for rect in group.iter():
            if not rect.tag.endswith("rect"):
                continue
            fill = rect.attrib.get("fill", "")
            if fill not in COLORS:
                raise ValueError(f"unknown fill {fill!r}: {path}")
            if fill not in color_index:
                color_index[fill] = len(palette)
                palette.append(COLORS[fill])
            x = float(rect.attrib["x"])
            y = float(rect.attrib["y"])
            w = float(rect.attrib["width"])
            h = float(rect.attrib["height"])
            # Fixed origin across all scenes: the character's feet are at
            # stage row 37, and alternate scenes do not jump horizontally.
            for cy in range(STAGE_H):
                sy = 156 + (cy + 0.5 - STAGE_H) * SCALE
                if not y <= sy < y + h:
                    continue
                for cx in range(STAGE_W):
                    sx = 100 + (cx + 0.5 - STAGE_W / 2) * SCALE
                    if x <= sx < x + w:
                        pixels[cy * STAGE_W + cx] = color_index[fill]
        frames.append(pixels)
    occupied = [(x, y) for frame in frames for y in range(STAGE_H)
                for x in range(STAGE_W) if frame[y * STAGE_W + x]]
    if not occupied:
        raise ValueError(f"no visible pixels after conversion: {path}")
    x0 = min(x for x, _ in occupied)
    y0 = min(y for _, y in occupied)
    x1 = max(x for x, _ in occupied) + 1
    y1 = max(y for _, y in occupied) + 1
    cropped = [[frame[y * STAGE_W + x] for y in range(y0, y1)
                for x in range(x0, x1)] for frame in frames]
    if len(palette) > 16:
        raise ValueError(f"too many colors: {path}")
    # These are discrete authored frames. For scenes with no per-frame hold
    # metadata, use their authored cycle duration divided over the frames.
    hold = max(50, round(duration_ms / len(frames)))
    return (x0, y0, x1 - x0, y1 - y0, palette, cropped,
            [hold] * len(frames))


def format_array(kind, name, values, columns=28):
    lines = [f"static const {kind} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), columns):
        chunk = values[i:i + columns]
        lines.append("    " + ",".join(f"0x{v:04X}" if kind == "uint16_t" else str(v)
                                    for v in chunk) + ",")
    return "\n".join(lines + ["};"])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--desktop", type=Path, default=Path.home() / "Projects/claude-desktop-pet/assets")
    parser.add_argument("--mascot", type=Path, default=Path.home() / "Projects/mascot-studio/public/mascot")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "firmware/src/pet_animations.h")
    args = parser.parse_args()
    lines = ["// Generated by tools/convert_pet_svg.py from the local Claude Desktop Pet",
             "// and Mascot Studio SVGs. See docs/pet-animation-library.md for provenance.",
             "// Do not edit by hand.", "#pragma once", "#include <stdint.h>",
             "#include \"splash_animations.h\"", ""]
    entries = []
    total = 0
    for name, source, filename in SCENES:
        path = (args.desktop if source == "desktop" else args.mascot) / filename
        x, y, w, h, palette, frames, holds = scene(path)
        ident = name.replace(" ", "_")
        flat = [value for frame in frames for value in frame]
        total += len(flat)
        lines.append(format_array("uint16_t", f"{ident}_palette", palette, 16))
        lines.append(format_array("uint8_t", f"{ident}_frames", flat))
        lines.append(format_array("uint16_t", f"{ident}_holds", holds, 20))
        lines.append("")
        entries.append(f'    {{"{name}", "pet", {w}, {h}, {x}, {y}, {len(frames)}, 0, {len(frames)-1}, {len(palette)}, {ident}_palette, {ident}_frames, {ident}_holds}},')
    lines.append(f"#define PET_ANIM_COUNT {len(entries)}")
    lines.append("static const splash_anim_def_t pet_anims[PET_ANIM_COUNT] = {")
    lines.extend(entries)
    lines.append("};")
    args.output.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.output}: {len(entries)} animations, {total} frame cells")


if __name__ == "__main__":
    main()
